"""
CPU-интенсивная вычислительная функция.
Используется в GUI и CLI режимах.
"""


def compute(n: int) -> int:
    """
    Вычисляет сумму квадратов от 1 до n.
    
    Аргументы:
        n: Верхняя граница вычисления
        
    Возвращает:
        Сумму квадратов от 1 до n
    """
    return sum(i * i for i in range(1, n + 1))
